let BLPAB_LANG = 'zh';
function blpabSetLang(pref) {
  const auto = /^zh/i.test((typeof navigator !== 'undefined' && navigator.language) || '') ? 'zh' : 'en';
  BLPAB_LANG = pref === 'zh' || pref === 'en' ? pref : auto;
  return BLPAB_LANG;
}
function t(key, vars) {
  if (BLPAB_LANG === 'en' && vars && vars.n === 1 && BLPAB_STRINGS.en[key + '1']) key += '1';
  const s = (BLPAB_STRINGS[BLPAB_LANG] || BLPAB_STRINGS.zh)[key] ?? BLPAB_STRINGS.zh[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? vars[k] : '')) : s;
}
